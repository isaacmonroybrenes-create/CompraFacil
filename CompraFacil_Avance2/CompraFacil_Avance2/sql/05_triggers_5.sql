CREATE OR REPLACE TRIGGER TRG_CATEGORIA_NOMBRE BEFORE INSERT OR UPDATE ON CATEGORIA FOR EACH ROW
BEGIN :NEW.NOMBRE := TRIM(:NEW.NOMBRE); END;
/

CREATE OR REPLACE TRIGGER TRG_PRODUCTO_NOMBRE BEFORE INSERT OR UPDATE ON PRODUCTO FOR EACH ROW
BEGIN :NEW.NOMBRE := TRIM(:NEW.NOMBRE); END;
/

CREATE OR REPLACE TRIGGER TRG_CLIENTE_CORREO BEFORE INSERT OR UPDATE ON CLIENTE FOR EACH ROW
BEGIN :NEW.CORREO := LOWER(TRIM(:NEW.CORREO)); END;
/

CREATE OR REPLACE TRIGGER TRG_PEDIDO_FECHA BEFORE INSERT ON PEDIDO FOR EACH ROW
BEGIN IF :NEW.FECHA_PEDIDO IS NULL THEN :NEW.FECHA_PEDIDO := SYSDATE; END IF; END;
/

CREATE OR REPLACE TRIGGER TRG_DETALLE_TOTAL
FOR INSERT OR UPDATE OR DELETE ON DETALLE_PEDIDO
COMPOUND TRIGGER
 TYPE t_ids IS TABLE OF NUMBER INDEX BY PLS_INTEGER;
 v_ids t_ids;
 v_n PLS_INTEGER := 0;
 PROCEDURE add_id(p_id NUMBER) IS BEGIN IF p_id IS NOT NULL THEN v_n:=v_n+1;v_ids(v_n):=p_id;END IF;END;
 AFTER EACH ROW IS
 BEGIN
  IF INSERTING OR UPDATING THEN add_id(:NEW.ID_PEDIDO); END IF;
  IF DELETING OR UPDATING THEN add_id(:OLD.ID_PEDIDO); END IF;
 END AFTER EACH ROW;
 AFTER STATEMENT IS
 BEGIN
  FOR i IN 1..v_n LOOP
   UPDATE PEDIDO p SET TOTAL=(SELECT NVL(SUM(d.SUBTOTAL),0) FROM DETALLE_PEDIDO d WHERE d.ID_PEDIDO=p.ID_PEDIDO)
   WHERE p.ID_PEDIDO=v_ids(i);
  END LOOP;
 END AFTER STATEMENT;
END;
/
