-- 10 paquetes: 5 de reportes (15 cursores explícitos), 5 de servicio.
CREATE OR REPLACE PACKAGE PKG_CATEGORIA_REPORTES AS
 PROCEDURE REPORTE_ORDENADO(p_resultado OUT SYS_REFCURSOR);
 FUNCTION CONTAR_CON_CURSOR RETURN NUMBER;
 FUNCTION MAX_ID_CON_CURSOR RETURN NUMBER;
END PKG_CATEGORIA_REPORTES;
/

CREATE OR REPLACE PACKAGE BODY PKG_CATEGORIA_REPORTES AS
 CURSOR c_orden IS SELECT ID_CATEGORIA FROM CATEGORIA ORDER BY ID_CATEGORIA;
 CURSOR c_cuenta IS SELECT ID_CATEGORIA FROM CATEGORIA;
 CURSOR c_maximo IS SELECT ID_CATEGORIA FROM CATEGORIA ORDER BY ID_CATEGORIA DESC;
 PROCEDURE REPORTE_ORDENADO(p_resultado OUT SYS_REFCURSOR) AS
 BEGIN OPEN p_resultado FOR SELECT * FROM CATEGORIA ORDER BY ID_CATEGORIA; END;
 FUNCTION CONTAR_CON_CURSOR RETURN NUMBER AS v NUMBER:=0;
 BEGIN FOR r IN c_cuenta LOOP v:=v+1; END LOOP; RETURN v; END;
 FUNCTION MAX_ID_CON_CURSOR RETURN NUMBER AS v NUMBER:=0;
 BEGIN FOR r IN c_maximo LOOP v:=r.ID_CATEGORIA; EXIT; END LOOP; RETURN v; END;
END PKG_CATEGORIA_REPORTES;
/

CREATE OR REPLACE PACKAGE PKG_CATEGORIA_SERVICIO AS
 PROCEDURE LISTAR(p_resultado OUT SYS_REFCURSOR);
 FUNCTION TOTAL_REGISTROS RETURN NUMBER;
END PKG_CATEGORIA_SERVICIO;
/

CREATE OR REPLACE PACKAGE BODY PKG_CATEGORIA_SERVICIO AS
 PROCEDURE LISTAR(p_resultado OUT SYS_REFCURSOR) AS BEGIN SP_CATEGORIA_LISTAR(p_resultado); END;
 FUNCTION TOTAL_REGISTROS RETURN NUMBER AS BEGIN RETURN FN_CATEGORIA_CONTAR(); END;
END PKG_CATEGORIA_SERVICIO;
/

