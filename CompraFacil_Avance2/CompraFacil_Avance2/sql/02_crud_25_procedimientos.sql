CREATE OR REPLACE PROCEDURE SP_CATEGORIA_CREAR(p_nombre IN VARCHAR2, p_descripcion IN VARCHAR2, p_id OUT NUMBER) AS
BEGIN
 INSERT INTO CATEGORIA (NOMBRE, DESCRIPCION) VALUES (p_nombre, p_descripcion) RETURNING ID_CATEGORIA INTO p_id;
END;
/

CREATE OR REPLACE PROCEDURE SP_CATEGORIA_ACTUALIZAR(p_id IN NUMBER, p_nombre IN VARCHAR2, p_descripcion IN VARCHAR2) AS
BEGIN
 UPDATE CATEGORIA SET NOMBRE=p_nombre, DESCRIPCION=p_descripcion WHERE ID_CATEGORIA=p_id;
 IF SQL%ROWCOUNT=0 THEN RAISE_APPLICATION_ERROR(-20001,'Registro inexistente'); END IF;
END;
/

CREATE OR REPLACE PROCEDURE SP_CATEGORIA_ELIMINAR(p_id IN NUMBER) AS
BEGIN
 DELETE FROM CATEGORIA WHERE ID_CATEGORIA=p_id;
 IF SQL%ROWCOUNT=0 THEN RAISE_APPLICATION_ERROR(-20001,'Registro inexistente'); END IF;
END;
/

CREATE OR REPLACE PROCEDURE SP_CATEGORIA_OBTENER(p_id IN NUMBER, p_resultado OUT SYS_REFCURSOR) AS
BEGIN
 OPEN p_resultado FOR SELECT * FROM CATEGORIA WHERE ID_CATEGORIA=p_id;
END;
/

CREATE OR REPLACE PROCEDURE SP_CATEGORIA_LISTAR(p_resultado OUT SYS_REFCURSOR) AS
BEGIN
 OPEN p_resultado FOR SELECT * FROM CATEGORIA ORDER BY ID_CATEGORIA;
END;
/

