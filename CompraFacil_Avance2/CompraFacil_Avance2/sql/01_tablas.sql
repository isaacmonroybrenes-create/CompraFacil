CREATE TABLE CATEGORIA (
  ID_CATEGORIA NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  NOMBRE VARCHAR2(100) NOT NULL,
  DESCRIPCION VARCHAR2(500)
);

CREATE TABLE PRODUCTO (
  ID_PRODUCTO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  ID_CATEGORIA NUMBER NOT NULL,
  NOMBRE VARCHAR2(150) NOT NULL,
  DESCRIPCION VARCHAR2(500),
  PRECIO NUMBER(12,2) NOT NULL,
  STOCK NUMBER(10) DEFAULT 0 NOT NULL,
  ESTADO VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
  CONSTRAINT FK_PROD_CAT FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIA(ID_CATEGORIA) ,
  CONSTRAINT CK_PROD_PRECIO CHECK (PRECIO >= 0) ,
  CONSTRAINT CK_PROD_STOCK CHECK (STOCK >= 0) ,
  CONSTRAINT CK_PROD_ESTADO CHECK (ESTADO IN ('ACTIVO','INACTIVO')) 
);

CREATE TABLE CLIENTE (
  ID_CLIENTE NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  NOMBRE VARCHAR2(100) NOT NULL,
  APELLIDOS VARCHAR2(150) NOT NULL,
  CORREO VARCHAR2(180) NOT NULL,
  TELEFONO VARCHAR2(30),
  DIRECCION VARCHAR2(300),
  FECHA_REGISTRO DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT UQ_CLIENTE_CORREO UNIQUE (CORREO) 
);

CREATE TABLE PEDIDO (
  ID_PEDIDO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  ID_CLIENTE NUMBER NOT NULL,
  FECHA_PEDIDO DATE DEFAULT SYSDATE NOT NULL,
  ESTADO VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
  TOTAL NUMBER(12,2) DEFAULT 0 NOT NULL,
  CONSTRAINT FK_PED_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE(ID_CLIENTE) ,
  CONSTRAINT CK_PED_TOTAL CHECK (TOTAL >= 0) ,
  CONSTRAINT CK_PED_ESTADO CHECK (ESTADO IN ('PENDIENTE','PAGADO','CANCELADO')) 
);

CREATE TABLE DETALLE_PEDIDO (
  ID_DETALLE NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  ID_PEDIDO NUMBER NOT NULL,
  ID_PRODUCTO NUMBER NOT NULL,
  CANTIDAD NUMBER(10) NOT NULL,
  PRECIO_UNITARIO NUMBER(12,2) NOT NULL,
  SUBTOTAL NUMBER(12,2) GENERATED ALWAYS AS (CANTIDAD * PRECIO_UNITARIO) VIRTUAL,
  CONSTRAINT FK_DET_PED FOREIGN KEY (ID_PEDIDO) REFERENCES PEDIDO(ID_PEDIDO) ON DELETE CASCADE ,
  CONSTRAINT FK_DET_PROD FOREIGN KEY (ID_PRODUCTO) REFERENCES PRODUCTO(ID_PRODUCTO) ,
  CONSTRAINT CK_DET_CANT CHECK (CANTIDAD > 0) ,
  CONSTRAINT CK_DET_PRECIO CHECK (PRECIO_UNITARIO >= 0) 
);
