-- 15 funciones: cantidad, maximo ID y existencia para cada tabla.
CREATE OR REPLACE FUNCTION FN_CATEGORIA_CONTAR RETURN NUMBER AS v NUMBER;
BEGIN SELECT COUNT(*) INTO v FROM CATEGORIA; RETURN v; END;
/

CREATE OR REPLACE FUNCTION FN_CATEGORIA_MAX_ID RETURN NUMBER AS v NUMBER;
BEGIN SELECT NVL(MAX(ID_CATEGORIA),0) INTO v FROM CATEGORIA; RETURN v; END;
/

CREATE OR REPLACE FUNCTION FN_CATEGORIA_EXISTE(p_id IN NUMBER) RETURN NUMBER AS v NUMBER;
BEGIN SELECT COUNT(*) INTO v FROM CATEGORIA WHERE ID_CATEGORIA=p_id; RETURN v; END;
/

