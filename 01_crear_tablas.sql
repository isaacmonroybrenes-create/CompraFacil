CREATE TABLE categoria (
    id_categoria NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR2(100) NOT NULL,
    descripcion  VARCHAR2(500)
);

CREATE TABLE producto (
    id_producto  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_categoria NUMBER NOT NULL,
    nombre       VARCHAR2(150) NOT NULL,
    descripcion  VARCHAR2(500),
    precio       NUMBER(10,2) NOT NULL,
    stock        NUMBER(10) DEFAULT 0 NOT NULL,
    estado       VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT fk_producto_categoria FOREIGN KEY (id_categoria) REFERENCES categoria(id_categoria),
    CONSTRAINT ck_producto_precio CHECK (precio >= 0),
    CONSTRAINT ck_producto_stock CHECK (stock >= 0),
    CONSTRAINT ck_producto_estado CHECK (estado IN ('ACTIVO','INACTIVO'))
);

CREATE TABLE cliente (
    id_cliente     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR2(100) NOT NULL,
    apellidos      VARCHAR2(150) NOT NULL,
    correo         VARCHAR2(254) NOT NULL,
    telefono       VARCHAR2(30),
    direccion      VARCHAR2(300),
    fecha_registro DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT uq_cliente_correo UNIQUE (correo)
);

CREATE TABLE pedido (
    id_pedido    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente   NUMBER NOT NULL,
    fecha_pedido DATE DEFAULT SYSDATE NOT NULL,
    estado       VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
    total        NUMBER(12,2) DEFAULT 0 NOT NULL,
    CONSTRAINT fk_pedido_cliente FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente),
    CONSTRAINT ck_pedido_estado CHECK (estado IN ('PENDIENTE','PROCESADO','ENTREGADO','CANCELADO')),
    CONSTRAINT ck_pedido_total CHECK (total >= 0)
);

CREATE TABLE detalle_pedido (
    id_detalle      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido       NUMBER NOT NULL,
    id_producto     NUMBER NOT NULL,
    cantidad        NUMBER(10) NOT NULL,
    precio_unitario NUMBER(10,2) NOT NULL,
    subtotal        NUMBER(12,2) NOT NULL,
    CONSTRAINT fk_detalle_pedido FOREIGN KEY (id_pedido) REFERENCES pedido(id_pedido),
    CONSTRAINT fk_detalle_producto FOREIGN KEY (id_producto) REFERENCES producto(id_producto),
    CONSTRAINT ck_detalle_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_detalle_precio CHECK (precio_unitario >= 0),
    CONSTRAINT ck_detalle_subtotal CHECK (subtotal >= 0)
);

CREATE INDEX ix_producto_categoria ON producto(id_categoria);
CREATE INDEX ix_pedido_cliente_fecha ON pedido(id_cliente, fecha_pedido);
CREATE INDEX ix_detalle_pedido ON detalle_pedido(id_pedido);
CREATE INDEX ix_detalle_producto ON detalle_pedido(id_producto);
